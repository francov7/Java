package fundamentos;

public class Clase02OperadoresAritmeticos {
    public static void main(String[] args) {

        int num1 = 4;
        int num2 = 2;
        int resultado = num1 + num2;

        System.out.println("El resultado de la suma es de: " + resultado);

        resultado = num1 - num2;
        System.out.println("El resultado de la resta es de: " + resultado);

        resultado = num1 * num2;
        System.out.println("El resultado de la multiplicadion es de: " + resultado);

        resultado = num1 / num2;
        System.out.println("El resultado de la division es de: " + resultado);

    }
}
