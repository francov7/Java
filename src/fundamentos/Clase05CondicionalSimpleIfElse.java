package fundamentos;

public class Clase05CondicionalSimpleIfElse {
    public static void main(String[] args) {

        int num1 = 15;
        int num2 = 10;

        if (num2 > num1) {
            System.out.println("El segundo es mayor.");
        } else {
            System.out.println("El primero es mayor.");
        }
    }
}
