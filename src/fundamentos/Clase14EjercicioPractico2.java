package fundamentos;

public class Clase14EjercicioPractico2 {
    public static void main(String[] args) {

        /*Realizar un programa que muestre por pantalla los numeros del 200 al 250
        saltando de 2 en 2, la secuencia deberia ser: 200, 202, 204, 206... etc
         */

        int i=200;

        while(i<=250){
            System.out.println(i);
            i = i+2;
        }
    }
}
